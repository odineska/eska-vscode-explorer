const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vscode = require('vscode');
const { until, frame } = require('./webview-host.cjs');
exports.run = async function() {
  const fixture=JSON.parse(process.env.ESKA_HOST_FIXTURE), form=fixture.form;
  const explorer=await vscode.extensions.all.find(extension=>extension.packageJSON.name==='eska-explorer').activate();
  await vscode.commands.executeCommand('eska.explorer.connect');
  const document=await vscode.workspace.openTextDocument(vscode.Uri.file(form.path));await vscode.window.showTextDocument(document,{preview:false});
  const before=await fs.readFile(form.pictureXml),original=await fs.readFile(form.one,'utf8');
  await vscode.commands.executeCommand('eska.explorer.previewForm');
  const service=explorer.formPreview;
  await until(()=>[...service.views.values()][0]?.phase==='ready','picture form ready');
  const view=[...service.views.values()][0],main=view.frames.get('main'),ui=await frame({state:{title:main.panel.title}});
  const image=()=>ui.evaluate("(()=>{const image=document.querySelector('.taxi-picture-resource');return image?.complete&&image.naturalWidth===16?image.src:null})()");
  await until(image,'common picture loaded as inert img');
  const first=await image();assert.equal(view.snapshot.model.assets.length,1);
  assert.ok(view.snapshot.dependencies.some(input=>input.role==='picture'));
  await fs.writeFile(form.one,original.replace('red','green'));
  await until(async()=>view.phase==='ready'&&(await image())!==first,'saved binary payload refreshes');
  const descriptor=await vscode.workspace.openTextDocument(vscode.Uri.file(form.pictureXml)),offset=descriptor.getText().indexOf('One.svg');
  const edit=new vscode.WorkspaceEdit();edit.replace(descriptor.uri,new vscode.Range(descriptor.positionAt(offset),descriptor.positionAt(offset+7)),'Two.svg');
  await vscode.workspace.applyEdit(edit);
  await until(()=>view.phase==='ready'&&view.snapshot.model.assets[0].picture.fileName==='Two.svg','dirty image descriptor changes selected payload');
  assert.deepEqual(await fs.readFile(form.pictureXml),before,'viewing does not save the picture descriptor');
  const expected=Buffer.from(await fs.readFile(form.two)).toString('base64');
  await until(async()=>(await image())?.endsWith(expected),'dirty image is rendered');
  await ui.screenshot(`form-pictures-${vscode.env.language}.png`);
  main.panel.dispose();await until(()=>service.views.size===0,'picture session released');await Promise.all([...service.closing]);
  await explorer.shutdown();await fs.writeFile(path.join(fixture.root,'host-result.json'),JSON.stringify({passed:true,formPictures:true,locale:vscode.env.language,externalPayload:true,dirtyPictureDescriptor:true,sourceWritesDuringViewing:false}));
};
