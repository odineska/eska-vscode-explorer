const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vscode = require('vscode');
const { frame, until, sameSourcePath } = require('./webview-host.cjs');

exports.run = async () => {
  const fixture = JSON.parse(process.env.ESKA_HOST_FIXTURE), form = fixture.form;
  const modulePath = path.join(path.dirname(form.path), 'Form', 'Module.bsl');
  await fs.writeFile(form.path, (await fs.readFile(form.path, 'utf8')).replace('</Form>', '<Commands><Command name="Probe" id="100"/></Commands></Form>'));
  const explorer = await vscode.extensions.all.find(item => item.packageJSON.name === 'eska-explorer').activate();
  await vscode.commands.executeCommand('eska.explorer.connect');
  const document = await vscode.workspace.openTextDocument(vscode.Uri.file(form.path));
  await vscode.window.showTextDocument(document, { preview: false });
  await vscode.commands.executeCommand('eska.explorer.previewForm');
  const service = explorer.formPreview;
  await until(() => service.views.size === 1 && [...service.views.values()][0].phase === 'ready', 'handler authoring form ready');
  const view = [...service.views.values()][0], main = view.frames.get('main');
  const ui = await frame({ fixedFormArea: true, state: { title: main.panel.title } });
  const button = event => `[data-palette-id="platform:${event}"] [data-edit-action="handler"]`;
  const click = async event => {
    main.panel.reveal();
    await until(() => ui.evaluate(`(() => { const button = document.querySelector(${JSON.stringify(button(event))}); if (!button || button.disabled) return false; button.click(); return true; })()`), 'event button ' + event);
  };
  await click('OnOpen');
  await until(async () => (await fs.readFile(form.path, 'utf8')).includes('<Event name="OnOpen">ПриОткрытии</Event>'), 'created handler bound and autosaved');
  const created = await fs.readFile(modulePath, 'utf8');
  assert.ok(created.includes('#Область ОбработчикиСобытийФормы'));
  assert.ok(created.includes('&НаКлиенте'));
  assert.ok(created.includes('Процедура ПриОткрытии(Отказ)'));
  assert.equal(vscode.window.activeTextEditor.document.getText(vscode.window.activeTextEditor.selection), 'ПриОткрытии');
  await click('OnOpen');
  await until(() => vscode.window.activeTextEditor && sameSourcePath(vscode.window.activeTextEditor.document.uri.fsPath, modulePath), 'repeat navigation');
  assert.equal(await fs.readFile(modulePath, 'utf8'), created, 'repeat does not create a second declaration');
  const module = await vscode.workspace.openTextDocument(vscode.Uri.file(modulePath));
  const edit = new vscode.WorkspaceEdit(); edit.insert(module.uri, new vscode.Position(0, 0), '// unsaved work\n');
  assert.equal(await vscode.workspace.applyEdit(edit), true);
  await click('OnOpen');
  await until(() => vscode.window.activeTextEditor?.document === module, 'dirty existing handler still navigates');
  assert.equal(module.isDirty, true);
  const before = await fs.readFile(form.path, 'utf8');
  await click('OnClose');
  await until(async () => !view.handlerEditing && await ui.evaluate(`!document.querySelector(${JSON.stringify(button('OnClose'))})?.disabled`), 'dirty creation refused');
  assert.equal(await fs.readFile(modulePath, 'utf8'), created, 'user dirty module is not saved');
  assert.equal(await fs.readFile(form.path, 'utf8'), before, 'failed handler creation leaves XML unbound');
  assert.equal(module.getText().includes('Процедура ПриЗакрытии('), false);
  await vscode.window.showTextDocument(module); await vscode.commands.executeCommand('workbench.action.files.revert');
  await click('OnClose');
  await until(async () => (await fs.readFile(form.path, 'utf8')).includes('<Event name="OnClose">ПриЗакрытии</Event>'), 'second event created');
  const output = await fs.readFile(modulePath, 'utf8');
  assert.equal(output.match(/#Область ОбработчикиСобытийФормы/g).length, 1, 'existing region reused');
  assert.ok(output.includes('Процедура ПриЗакрытии(ЗавершениеРаботы)'));
  const config = vscode.workspace.getConfiguration('files');
  await config.update('readonlyInclude', { '**/Module.bsl': true }, vscode.ConfigurationTarget.Workspace);
  const boundBeforeLock = await fs.readFile(form.path, 'utf8');
  await click('OnCreateAtServer');
  await until(async () => !view.handlerEditing && await ui.evaluate(`!document.querySelector(${JSON.stringify(button('OnCreateAtServer'))})?.disabled`), 'read-only creation refused');
  assert.equal(await fs.readFile(modulePath, 'utf8'), output);
  assert.equal(await fs.readFile(form.path, 'utf8'), boundBeforeLock);
  await config.update('readonlyInclude', undefined, vscode.ConfigurationTarget.Workspace);
  main.panel.reveal();
  await ui.evaluate("document.querySelector('.taxi-input').click()");
  await click('OnChange');
  await until(async () => (await fs.readFile(form.path, 'utf8')).includes('<Event name="OnChange">NameПриИзменении</Event>'), 'field event bound');
  assert.ok((await fs.readFile(modulePath, 'utf8')).includes('Процедура NameПриИзменении(Элемент)'));
  assert.ok((await fs.readFile(modulePath, 'utf8')).includes('#Область ОбработчикиСобытийЭлементовШапкиФормы'));
  main.panel.reveal();
  await ui.evaluate(`([...document.querySelectorAll('.form-inspectors .form-tabs button')].find(button => button.textContent === ${JSON.stringify(vscode.env.language.startsWith('ru') ? 'Команды' : 'Commands')})).click()`);
  await ui.evaluate("document.querySelector('.form-data-row[data-form-data-path=Probe]').click()");
  await until(() => ui.evaluate("(() => { const button = document.querySelector('[data-edit-property=Action]')?.parentElement.querySelector('[data-edit-action=handler]'); if (!button || button.disabled) return false; button.click(); return true; })()"), 'command handler button');
  await until(async () => (await fs.readFile(form.path, 'utf8')).includes('<Action>Probe</Action>'), 'command action bound');
  const commandCode = await fs.readFile(modulePath, 'utf8');
  assert.ok(commandCode.includes('Процедура Probe(Команда)'));
  assert.ok(commandCode.includes('#Область ОбработчикиКомандФормы'));
  await ui.screenshot(`form-handler-authoring-${vscode.env.language}.png`);
  ui.close(); await explorer.shutdown();
  await fs.writeFile(path.join(fixture.root, 'host-result.json'), JSON.stringify({ passed: true, scenario: 'form-handler-authoring', assertions: ['missing-module', 'missing-region', 'existing-region', 'idempotency', 'dirty-navigation', 'dirty-create-blocked', 'bind-after-save', 'actual-ui-button', 'read-only-module', 'field-handler', 'command-handler'] }));
};
